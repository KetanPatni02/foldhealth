// patient_outreach row ↔ outreach entry, shared by the store and the seed.

export function patientOutreachToRow(e) {
  return {
    id: String(e.id),
    patient_key: e.patientKey,
    patient_name: e.patientName ?? null,
    program: e.program || 'RA',
    recipient_type: e.recipientType,
    received_by: e.receivedBy ?? null,
    mode: e.mode,
    direction: e.mode === 'Call' ? (e.direction || 'outgoing') : null,
    call_via: e.callVia ?? null,
    called_to: e.calledTo ?? null,
    duration_sec: e.durationSec ?? null,
    transcript: e.transcript || null,
    email_to: e.emailTo || null,
    email_subject: e.emailSubject || null,
    email_body: e.emailBody || null,
    notes: e.notes || '',
    category: e.category,
    outcome: e.category === 'Note' ? null : (e.outcome || null),
    logged_by: e.loggedBy || '',
    logged_by_role: e.loggedByRole ?? null,
    logged_at: e.loggedAt,
    snooze_until: e.snoozeUntil ?? null,
    corrects_id: e.correctsId ?? null,
    pcp_outreach_id: e.pcpOutreachId ?? null,
    hcc_refs: e.hccRefs || [],
    ai_status: e.aiStatus === 'pending' ? 'none' : (e.aiStatus || 'none'),
    ai_call_summary: e.aiCallSummary ?? null,
    ai_patient_actions: e.aiPatientActions ?? null,
  };
}

export function rowToPatientOutreach(r) {
  return {
    id: r.id,
    patientKey: r.patient_key,
    patientName: r.patient_name,
    program: r.program,
    recipientType: r.recipient_type,
    receivedBy: r.received_by,
    mode: r.mode,
    direction: r.direction,
    callVia: r.call_via,
    calledTo: r.called_to,
    durationSec: r.duration_sec,
    transcript: r.transcript,
    emailTo: r.email_to,
    emailSubject: r.email_subject,
    emailBody: r.email_body,
    notes: r.notes || '',
    category: r.category,
    outcome: r.outcome,
    loggedBy: r.logged_by,
    loggedByRole: r.logged_by_role,
    loggedAt: r.logged_at,
    snoozeUntil: r.snooze_until,
    correctsId: r.corrects_id,
    pcpOutreachId: r.pcp_outreach_id,
    hccRefs: r.hcc_refs || [],
    aiStatus: r.ai_status || 'none',
    aiCallSummary: r.ai_call_summary,
    aiPatientActions: r.ai_patient_actions || [],
  };
}
