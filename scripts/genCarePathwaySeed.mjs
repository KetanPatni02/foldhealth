// Writes supabase/care_pathways_seed.sql from the Fold pathway content
// (src/features/settings/care-plan-library/data/carePathwayContent.js), so the
// SQL never drifts from what the app and its tests read.
//
//   bun scripts/genCarePathwaySeed.mjs
//
// The seed upserts every pathway by id; a pathway whose content changed gets
// a new updated_at. Run it after care_pathways_migration.sql.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CARE_PATHWAY_CONTENT } from '../src/features/settings/care-plan-library/data/carePathwayContent.js';
import { pathwayToRow } from '../src/features/settings/care-plan-library/lib/carePathways.js';

const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
const textArray = (a) => (a.length ? `ARRAY[${a.map(lit).join(', ')}]` : `ARRAY[]::text[]`);

const values = CARE_PATHWAY_CONTENT.map((p, i) => {
  const r = pathwayToRow(p, i);
  return `  (${[lit(r.id), lit(r.name), lit(r.condition), lit(r.version), lit(r.summary), textArray(r.sources),
    json(r.gbi), json(r.decision_logic), json(r.cadence), r.sort_order].join(',\n   ')})`;
});

const sql = `-- Generated by scripts/genCarePathwaySeed.mjs from
-- src/features/settings/care-plan-library/data/carePathwayContent.js.
-- Do not hand-edit: change the content file and regenerate.

INSERT INTO public.care_pathways (id, name, condition, version, summary, sources, gbi, decision_logic, cadence, sort_order)
VALUES
${values.join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  condition = EXCLUDED.condition,
  version = EXCLUDED.version,
  summary = EXCLUDED.summary,
  sources = EXCLUDED.sources,
  gbi = EXCLUDED.gbi,
  decision_logic = EXCLUDED.decision_logic,
  cadence = EXCLUDED.cadence,
  sort_order = EXCLUDED.sort_order,
  updated_at = CASE
    WHEN (care_pathways.version, care_pathways.gbi, care_pathways.decision_logic, care_pathways.cadence, care_pathways.summary)
      IS DISTINCT FROM (EXCLUDED.version, EXCLUDED.gbi, EXCLUDED.decision_logic, EXCLUDED.cadence, EXCLUDED.summary)
    THEN now() ELSE care_pathways.updated_at END;
`;

const out = fileURLToPath(new URL('../supabase/care_pathways_seed.sql', import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${CARE_PATHWAY_CONTENT.length} pathways to supabase/care_pathways_seed.sql`);
